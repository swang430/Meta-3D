// 真实前后端、独立临时数据库，全HAL Mock；不拦截网络或伪造仪器读数。
async page => {
  const api='http://127.0.0.1:18080/api/v1', checks=[];
  await page.setViewportSize({width:1600,height:1000});
  page.setDefaultTimeout(12000);
  const status=await(await page.request.get(`${api}/instruments/hal/status`)).json();
  if(status.mode!=='mock')throw new Error('只能使用全Mock临时后端');
  const labs=await(await page.request.get(`${api}/lab-profiles`)).json();
  const lab=labs.find(l=>l.name==='PC04自动采集甲');
  for(const category of ['channelEmulator','signalAnalyzer']){
    const catalog=await(await page.request.get(`${api}/instruments/catalog`)).json();
    const c=catalog.categories.find(c=>c.key===category);
    const synced=await page.request.put(`${api}/lab-profiles/${lab.id}/instrument-bindings/${category}/sync-current`,{data:{expected_saved_configuration_digest:c.savedConfigurationDigest}});
    if(!synced.ok())throw new Error(await synced.text());
  }
  await page.goto('http://127.0.0.1:5187');
  await page.evaluate(id=>localStorage.setItem('mimo.operationalLabProfileId',id),lab.id);
  await page.reload();
  await page.getByRole('tab',{name:'实验室配置',exact:true}).click();
  if(await page.getByTestId('fixed-route-acquisition').count())throw new Error('旧的独立采集卡尚未撤除');
  if(await page.getByTestId('calibration-scope').count())throw new Error('总览仍堆叠校准表单');
  checks.push('总览撤除校准卡片');
  await page.getByRole('tab',{name:'射频拓扑',exact:true}).click();
  const workspace=page.getByTestId('topology-calibration');
  await workspace.waitFor();
  await workspace.getByRole('button',{name:'选择校准通路 B1.1 探头0 V',exact:true}).click();
  for(const title of ['空口传播','参考天线','接收线缆','信号分析仪','整条通路测量'])await workspace.getByText(title,{exact:true}).first().waitFor();
  checks.push('图上选B1.1，补齐空口至分析仪的完整测量路径');
  if(await workspace.getByLabel('采集链路',{exact:false}).count())throw new Error('侧栏还存在第二套链路选择');
  for(const[label,value]of[['采集频率','2595'],['允许的单音设置功率','-20'],['参考天线身份','SN-REF 静区中心V'],['接收线缆损耗','2'],['接收线缆记录来源','SN-CABLE 2595MHz']])await workspace.getByLabel(label,{exact:false}).fill(value);
  await workspace.getByRole('checkbox',{name:'我已核对所选链',exact:false}).check();
  await workspace.getByRole('checkbox',{name:'我已确认专用校准仿真',exact:false}).check();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/fixed-route-acquisitions')&&r.request().method()==='POST');
  await workspace.getByRole('button',{name:'开始自动采集',exact:true}).click();
  const response=await responsePromise;
  if(response.status()!==202)throw new Error(await response.text());
  const created=await response.json();
  await workspace.getByText('模拟流程完成（无真实测量）',{exact:true}).first().waitFor();
  const record=await(await page.request.get(`${api}/lab-profiles/${lab.id}/fixed-route-acquisitions/${created.run_id}`)).json();
  if(record.result.request.chain_id!=='fixed-v'||record.result.net_loss_db!==null||record.result.samples.length)throw new Error(JSON.stringify(record));
  checks.push('图选通路进入真实POST，模拟没有实测功率与损耗');
  if(!await workspace.getByRole('button',{name:'确认采用为参考',exact:true}).isDisabled())throw new Error('模拟允许采用');
  const adopted=await page.request.post(`${api}/lab-profiles/${lab.id}/fixed-route-acquisitions/${created.run_id}/reference`,
    {data:{expected_configuration_digest:record.result.request.configuration_digest,operator_confirmed:true}});
  if(adopted.status()!==422)throw new Error('服务器放行模拟采用');
  checks.push('图内和服务器均拒绝将模拟记录采用为实测参考');
  await workspace.getByTestId('calibration-graph').scrollIntoViewIfNeeded();
  await workspace.getByTestId('calibration-graph').evaluate(el=>el.scrollIntoView({block:'end'}));
  await workspace.getByTestId('calibration-graph').screenshot({path:'output/playwright/topology-calibration-graph.png'});
  await page.screenshot({path:'output/playwright/topology-calibration-desktop.png',fullPage:true});
  await page.setViewportSize({width:900,height:1000});
  await workspace.getByTestId('calibration-graph').scrollIntoViewIfNeeded();
  await workspace.getByTestId('calibration-graph').getByRole('button',{name:'Fit View',exact:true}).click();
  await workspace.getByTestId('calibration-graph').evaluate(el=>el.scrollIntoView({block:'end'}));
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2))throw new Error('页面横向溢出');
  await workspace.getByTestId('calibration-graph').screenshot({path:'output/playwright/topology-calibration-narrow.png'});
  checks.push('窄窗口图文无页面横向溢出');
  await page.setViewportSize({width:1600,height:1000});
  await workspace.getByRole('button',{name:'查看全部通路',exact:true}).click();
  await workspace.getByRole('button',{name:'选择校准通路 B1.2 探头0 H',exact:true}).click();
  if(await workspace.getByLabel('采集频率',{exact:false}).inputValue())throw new Error('换通路沿用旧输入');
  await workspace.getByText('F64 输出 B1.2',{exact:true}).first().waitFor();
  checks.push('图切另一通路，端口正确且输入不串用');
  for(const[label,value]of[['采集频率','2595'],['允许的单音设置功率','-20'],['参考天线身份','SN-REF H'],['重复采样次数','10']])
    await workspace.getByLabel(label,{exact:false}).fill(value);
  await workspace.getByRole('checkbox',{name:'我已核对所选链',exact:false}).check();
  await workspace.getByRole('checkbox',{name:'我已确认专用校准仿真',exact:false}).check();
  const begun=page.waitForResponse(r=>r.url().endsWith('/fixed-route-acquisitions')&&r.request().method()==='POST');
  await workspace.getByRole('button',{name:'开始自动采集',exact:true}).click();
  const second=await(await begun).json();
  const cancelled=page.waitForResponse(r=>r.url().endsWith(`/${second.run_id}/cancel`));
  await workspace.getByRole('button',{name:'取消采集并停止本次单音',exact:true}).click();
  if(!(await cancelled).ok())throw new Error('取消请求失败');
  await workspace.getByText('已取消',{exact:true}).first().waitFor();
  checks.push('真实任务编号取消，模拟取消不伪称真实停发');
  await page.context().setOffline(true);
  await workspace.getByRole('button',{name:'重新读取配置',exact:true}).click();
  await workspace.getByText('网络离线，尚未确认仪器已停止。请恢复网络后重新读取配置。',{exact:true}).waitFor();
  if(!await page.getByRole('button',{name:'连接编辑',exact:true}).isDisabled())throw new Error('离线仍允许改接线');
  await page.context().setOffline(false);
  await workspace.getByRole('button',{name:'重新读取配置',exact:true}).click();
  await page.getByRole('button',{name:'连接编辑',exact:true}).click();
  await page.getByRole('button',{name:'通路校准',exact:true}).click();
  checks.push('离线禁止改接线；恢复后可重读并切换连接编辑');
  await workspace.getByRole('button',{name:'选择校准通路 B1.1 探头0 V',exact:true}).click();
  const old=workspace.getByRole('button',{name:'查看记录',exact:true});
  await old.first().click();
  await workspace.getByText('模拟流程完成（无真实测量）',{exact:true}).first().waitFor();
  checks.push('返回原通路可查看服务器历史，不借另一通路结果');
  await workspace.getByRole('button',{name:'配置复核',exact:true}).click();
  await page.getByRole('heading',{name:'配置复核',exact:true}).waitFor();
  if(await page.getByTestId('calibration-scope').locator('table').count())throw new Error('仍以通路表格代替图');
  await page.keyboard.press('Escape');
  await workspace.getByRole('button',{name:'F64状态',exact:true}).click();
  await page.getByRole('heading',{name:'F64状态与历史',exact:true}).waitFor();
  await page.keyboard.press('Escape');
  checks.push('配置复核和F64状态只在图内辅助面板打开');
  const other=labs.find(l=>l.name==='PC04自动采集乙');
  await page.getByRole('textbox',{name:'当前 LabProfile',exact:true}).click();
  await page.getByRole('option',{name:/PC04自动采集乙/}).click();
  await page.getByTestId('topology-calibration').getByRole('button',{name:'选择校准通路 B1.1 探头0 V',exact:true}).click();
  if(await page.getByTestId('topology-acquisition-panel').getByLabel('采集频率',{exact:false}).inputValue())throw new Error('换实验室沿用旧输入');
  const denied=await page.request.get(`${api}/lab-profiles/${other.id}/fixed-route-acquisitions/${created.run_id}`);
  if(denied.status()!==404)throw new Error('记录跨实验室可读');
  checks.push('实验室切换清空输入；服务器拒绝跨实验室读取');
  return{passed:checks.length,checks,run_id:created.run_id};
}
